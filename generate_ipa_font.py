#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Write the IPA webfont link into the pages that show IPA.

Google serves Charis SIL in unicode-range subsets, and from the combining
block those subsets carry only U+0300, U+0301, U+0303, U+0304, U+0308,
U+0309, U+0323 and U+0329. Everything else the IPA here uses — the tie bar
above all, 283 times — was being drawn by whatever other font the browser
could find. A combining mark only positions correctly against a base from
the same font resource, so the tie bar in /t͡ɕi.ɯt̚/ sat over the slash.

Google will cut a subset to order with `text=`, so the fix is to ask for
exactly the characters the IPA uses, as one face. It has to be one face and
not a second one holding only the marks: two @font-face rules are two font
resources, and a mark in one cannot position against a base in the other.

The link is generated rather than written by hand because a character
missing from it falls back silently, which is the bug this fixes.

    python3 generate_ipa_font.py
"""
import glob
import io
import json
import os
import re
import urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
PAGES = ["script.html", "study.html"]
MARK = "ipa-font"

# Punctuation the pages print around a transcription, plus the stress and
# length marks, so a card is never split across two faces.
ALWAYS = "/[](){}.,:;-–— ˈˌːˑ"


def ipa_text():
    """Every character any IPA string on the site uses."""
    chars = set(ALWAYS)

    def scan(s):
        if s:
            chars.update(s)

    for path in sorted(glob.glob(os.path.join(HERE, "assets/data/scripts/*.json"))):
        doc = json.load(io.open(path, encoding="utf-8"))
        if "letters" not in doc:
            continue
        for L in doc["letters"]:
            scan(L.get("name_ipa"))
            scan(L.get("example_ipa"))
            for v in (L.get("ipa") or []):
                scan(v)
        for key in (doc.get("ipa_links") or {}):
            scan(key)
    for path in sorted(glob.glob(os.path.join(HERE, "assets/data/words/*.json"))):
        for w in json.load(io.open(path, encoding="utf-8"))["words"]:
            scan(w.get("ipa"))
    pang = os.path.join(HERE, "assets/data/pangrams.json")
    if os.path.exists(pang):
        for p in json.load(io.open(pang, encoding="utf-8"))["pangrams"]:
            scan(p.get("ipa"))

    chars = {c for c in chars if c.strip() or c == " "}
    return "".join(sorted(chars, key=ord))


def link_tag(text):
    url = ("https://fonts.googleapis.com/css2?family=Charis+SIL:wght@400;700"
           "&display=swap&text=" + urllib.parse.quote(text, safe=""))
    return ('    <!-- %s: Charis SIL cut to the characters the IPA here uses, '
            'so a mark and its base come from one face. Generated by '
            'generate_ipa_font.py. -->\n'
            '    <link rel="stylesheet" href="%s" />' % (MARK, url))


def main():
    text = ipa_text()
    tag = link_tag(text)
    pattern = re.compile(
        r"[ \t]*<!-- %s:.*?-->\n[ \t]*<link rel=\"stylesheet\" href=\"https://fonts\.googleapis\.com/css2\?family=Charis\+SIL[^\"]*\" />"
        % MARK, re.S)
    for page in PAGES:
        path = os.path.join(HERE, page)
        s = io.open(path, encoding="utf-8").read()
        if pattern.search(s):
            s = pattern.sub(lambda _m: tag, s)
        else:
            # put it after the general font link, so it wins for these glyphs
            anchor = re.search(r"[ \t]*href=\"https://fonts\.googleapis\.com/css2\?family=Charis\+SIL[^\"]*\" />",
                               s)
            if not anchor:
                print("  %s: no Google Fonts link to sit after" % page)
                continue
            s = s[:anchor.end()] + "\n" + tag + s[anchor.end():]
        io.open(path, "w", encoding="utf-8").write(s)
        print("  %s: linked" % page)
    print("%d characters, %d bytes of URL" % (len(text), len(tag)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
